/**
 * Регулярные выражения для обработки ответов клиентов на приветствие голосового ассистента
 * Фраза: "Привет. Меня зовут Лиза - я голосовой помощник"
 *
 * Используется подход на основе корней слов для учета различных словоформ и склонений
 */

class VoiceAssistantPatterns {

    // =====================================================
    // 1. ПРИВЕТСТВИЯ
    // =====================================================

    /**
     * Простые приветствия: привет, здравствуй, добрый день и т.д.
     */
    static final GREETINGS = [
        // Привет + вариации
        ~/(?i).*\b(привет|приветик|приветствую|приветики)\b.*/,

        // Здравствуй + все формы (здравствуй, здравствуйте)
        ~/(?i).*\b(здравству|здорово|здрасьте|здрасти)\w*\b.*/,

        // Добрый + время суток (день/утро/вечер)
        ~/(?i).*\b(добр\w*)\s+(день|утро|вечер|ночь)\b.*/,

        // Неформальные приветствия
        ~/(?i).*\b(хай|хэй|хелло|йо|алло)\b.*/,

        // Вечер добрый, день добрый и т.д. (обратный порядок)
        ~/(?i).*\b(день|утро|вечер)\s+(добр\w*)\b.*/
    ]

    // =====================================================
    // 2. ВЕЖЛИВЫЕ ОТВЕТЫ / БЛАГОДАРНОСТЬ
    // =====================================================

    /**
     * Выражения вежливости: приятно, спасибо, рад слышать
     */
    static final POLITE_RESPONSES = [
        // Приятно познакомиться + вариации
        ~/(?i).*\b(приятн\w*)\s*(познаком\w*|слышать|видеть)?\b.*/,

        // Рад/рада + что-то (слышать, познакомиться, с вами)
        ~/(?i).*\b(рад|рада|радо|рады)\b.*(слышать|познаком\w*|вас|тебя|вами)?.*/,

        // Спасибо + вариации (спасибо, благодарю)
        ~/(?i).*\b(спасиб\w*|благодар\w*|признател\w*)\b.*/,

        // Хорошо + согласие
        ~/(?i).*\b(хорошо|отлично|замечательно|прекрасно|супер|отличн\w*)\b.*/,

        // Взаимно
        ~/(?i).*\b(взаимн\w*|мне\s+тоже)\b.*/
    ]

    // =====================================================
    // 3. СОГЛАСИЕ / ПОДТВЕРЖДЕНИЕ
    // =====================================================

    /**
     * Выражения согласия: да, слушаю, понял/поняла
     */
    static final CONFIRMATIONS = [
        // Да + вариации (да, ага, угу, ну да)
        ~/(?i)^\s*(да|ага|угу|ок|окей|ладно)\s*$/,
        ~/(?i).*\b(ну\s+)?(да|ага|угу)\b.*/,

        // Слушаю + вариации
        ~/(?i).*\b(слуша\w*|слышу)\b.*/,

        // Понял/поняла + все формы
        ~/(?i).*\b(понял|поняла|поняли|понятн\w*|ясно|понял\w*)\b.*/,

        // Го, давай, вперед
        ~/(?i).*\b(давай\w*|вперед|продолжай\w*|го|погнали)\b.*/
    ]

    // =====================================================
    // 4. ВОПРОСЫ О ВОЗМОЖНОСТЯХ / ПОМОЩИ
    // =====================================================

    /**
     * Вопросы о функциях ассистента: что умеешь, чем поможешь
     */
    static final CAPABILITY_QUESTIONS = [
        // Что ты умеешь / можешь
        ~/(?i).*\b(что|а\s+что)\s+(ты|вы)\s+(умее\w*|може\w*|делае\w*)\b.*/,

        // Чем можешь помочь / помогаешь
        ~/(?i).*\b(чем|в\s+чем|как)\s+(може\w*|помог\w*|помоч\w*|помощ\w*)\b.*/,

        // Что ты предлагаешь / что будет
        ~/(?i).*\b(что)\s+(предлага\w*|будет|дальше|потом)\b.*/,

        // Для чего ты / зачем ты
        ~/(?i).*\b(для\s+чего|зачем|с\s+какой\s+целью)\s+(ты|вы)\b.*/,

        // Какие у тебя функции / возможности
        ~/(?i).*\b(как\w*)\s+(функ\w*|возможн\w*|услуг\w*|опци\w*)\b.*/
    ]

    // =====================================================
    // 5. ВОПРОСЫ ПРО ДЕЛА / САМОЧУВСТВИЕ
    // =====================================================

    /**
     * Вопросы про дела: как дела, как настроение и т.д.
     */
    static final SMALL_TALK = [
        // Как дела / как ты / как у тебя
        ~/(?i).*\b(как)\s+(дела|у\s+(тебя|вас)|ты|вы|сам\w*|настроен\w*|поживае\w*)\b.*/,

        // Что нового / как жизнь
        ~/(?i).*\b(что|как)\s+(нов\w*|жизнь|житье)\b.*/,

        // Все хорошо? / все нормально?
        ~/(?i).*\b(все|всё)\s+(хорош\w*|нормальн\w*|в\s+порядк\w*|ок\w*)\b.*/
    ]

    // =====================================================
    // 6. ВОПРОСЫ ИДЕНТИФИКАЦИИ
    // =====================================================

    /**
     * Вопросы про личность ассистента: кто ты, откуда, представься
     */
    static final IDENTITY_QUESTIONS = [
        // Кто ты / ты кто / кто говорит
        ~/(?i).*\b(кто)\s+(ты|вы|это|говор\w*|звон\w*)\b.*/,
        ~/(?i).*\b(ты|вы)\s+(кто)\b.*/,

        // Представься / назови себя / твое имя
        ~/(?i).*\b(представ\w*|назов\w*|скажи\w*)\s+(себя|имя|как\s+зовут)\b.*/,
        ~/(?i).*\b(как\s+(тебя|вас)|твое\s+имя|ваше\s+имя)\s*(зовут|называ\w*)?\b.*/,

        // Откуда ты / откуда звонишь
        ~/(?i).*\b(откуда)\s+(ты|вы|звон\w*|говор\w*)\b.*/,

        // Ты кто такая / кто такой
        ~/(?i).*\b(кто\s+так\w*)\b.*/
    ]

    // =====================================================
    // 7. ВОПРОСЫ О ПРИЧИНЕ ЗВОНКА
    // =====================================================

    /**
     * Вопросы о цели звонка: зачем звонишь, что нужно, по какому вопросу
     */
    static final PURPOSE_QUESTIONS = [
        // Зачем звонишь / почему звонишь
        ~/(?i).*\b(зачем|почему|по\s+как\w*\s+причин\w*)\s+(звон\w*|звоним\w*)\b.*/,

        // Что нужно / что надо / что хотите
        ~/(?i).*\b(что|чего)\s+(нужн\w*|надо|хоти\w*|треб\w*)\b.*/,

        // По какому вопросу / поводу
        ~/(?i).*\b(по\s+как\w*)\s+(вопрос\w*|повод\w*|делу)\b.*/,

        // В чем дело / что случилось
        ~/(?i).*\b(в\s+чем|что)\s+(дело|случил\w*|происход\w*)\b.*/,

        // Какая цель звонка
        ~/(?i).*\b(как\w*)\s+(цель|смысл)\b.*(звонк\w*|звон\w*)?.*/
    ]

    // =====================================================
    // 8. ОТКАЗЫ / НЕГАТИВНЫЕ РЕАКЦИИ
    // =====================================================

    /**
     * Негативные реакции: отстань, не нужно, не интересно
     */
    static final REJECTIONS = [
        // Отстань / отвали / уйди
        ~/(?i).*\b(отстань|отвали|уйди|отъебись|свали|отвян\w*)\b.*/,

        // Не нужно / не надо / не хочу
        ~/(?i).*\b(не\s+(нужн\w*|надо|хочу|интересн\w*|требуется))\b.*/,

        // Повесь трубку / положи трубку / до свидания
        ~/(?i).*\b(повесь|положи|брось|кинь)\s+(трубк\w*)\b.*/,
        ~/(?i).*\b(до\s+свидан\w*|всего\s+добр\w*|прощай\w*|пока)\b.*/,

        // Не звони / не беспокой
        ~/(?i).*\b(не\s+(звони\w*|беспокой\w*|трево\w*|дёргай\w*))\b.*/,

        // Мне это не интересно
        ~/(?i).*\b(мне)\s+(это\s+)?(не\s+)?(интересн\w*|нужн\w*)\b.*/,

        // Уберите меня из базы / удалите мой номер
        ~/(?i).*\b(убер\w*|удал\w*|исключ\w*)\s+(меня|мой\s+номер|из\s+баз\w*)\b.*/
    ]

    // =====================================================
    // 9. ПЕРЕСПРОС / НЕПОНИМАНИЕ
    // =====================================================

    /**
     * Выражения непонимания: что, а, не расслышал
     */
    static final CLARIFICATIONS = [
        // Что? / Чего? / А?
        ~/(?i)^\s*(что|чего|а|ась|га|чё|чево)\s*\??\s*$/,

        // Не расслышал / не слышу / плохо слышно
        ~/(?i).*\b(не\s+(расслыша\w*|слыш\w*|понял\w*))\b.*/,
        ~/(?i).*\b(плох\w*)\s+(слышн\w*|понятн\w*|слыш\w*)\b.*/,

        // Повтори / повторите
        ~/(?i).*\b(повтор\w*|еще\s+раз|можно\s+еще|что\s+сказал\w*)\b.*/,

        // Извините, что?
        ~/(?i).*\b(извин\w*|прости\w*|пардон)\b.*(что|чего|не\s+понял|не\s+расслыша\w*)?.*/,

        // Громче / тише
        ~/(?i).*\b(громче|тише|громкость|погромче|потише)\b.*/
    ]

    // =====================================================
    // 10. ОЖИДАНИЕ / ПРОСЬБА ПОДОЖДАТЬ
    // =====================================================

    /**
     * Просьбы подождать: секунду, минутку, сейчас
     */
    static final WAIT_REQUESTS = [
        // Секунду / минуту / момент
        ~/(?i).*\b(секунд\w*|минут\w*|момент|мгновени\w*)\b.*/,

        // Сейчас / щас / счас
        ~/(?i).*\b(сейчас|щас|счас|погод\w*|подожд\w*)\b.*/,

        // Одну секунду / один момент
        ~/(?i).*\b(од\w*)\s+(секунд\w*|минут\w*|момент)\b.*/
    ]

    // =====================================================
    // 11. ЗАНЯТ / НЕЛЬЗЯ ГОВОРИТЬ
    // =====================================================

    /**
     * Сообщения о занятости: я занят, не могу говорить, перезвоните
     */
    static final BUSY_RESPONSES = [
        // Я занят / занята
        ~/(?i).*\b(я|сейчас)\s+(занят|занята|занято|занят\w*)\b.*/,

        // Не могу говорить / разговаривать
        ~/(?i).*\b(не\s+могу|нельзя|некогда)\s+(говор\w*|разговар\w*|общ\w*)\b.*/,

        // Перезвоните / позвоните позже
        ~/(?i).*\b(перезвон\w*|позвон\w*|звони\w*)\s+(позже|потом|попозже)\b.*/,

        // Я за рулем / я еду / я на работе
        ~/(?i).*\b(я|сейчас)\s+(за\s+рулем|еду|ед\w*|на\s+работ\w*|на\s+совещ\w*|на\s+встреч\w*)\b.*/,

        // Не время / неудобно
        ~/(?i).*\b(не\s+врем\w*|неудобн\w*|не\s+подходящ\w*\s+момент)\b.*/
    ]

    // =====================================================
    // 12. ВОПРОСЫ О БОТЕ / РОБОТЕ
    // =====================================================

    /**
     * Вопросы о том, является ли собеседник роботом
     */
    static final BOT_QUESTIONS = [
        // Ты робот / ты бот
        ~/(?i).*\b(ты|вы)\s+(робот|бот|машин\w*|компьютер|автомат)\b.*/,

        // Это автоответчик / это запись
        ~/(?i).*\b(это)\s+(автоответч\w*|запись|автомат\w*|робот)\b.*/,

        // С кем я говорю / живой человек?
        ~/(?i).*\b(живой|настоящ\w*|реальн\w*)\s+(человек|собеседн\w*)\b.*/,
        ~/(?i).*\b(с\s+кем)\s+(я\s+)?(говор\w*|общ\w*)\b.*/
    ]

    // =====================================================
    // ВСПОМОГАТЕЛЬНЫЕ МЕТОДЫ
    // =====================================================

    /**
     * Проверяет, соответствует ли текст хотя бы одному паттерну в категории
     *
     * @param text Входной текст для проверки
     * @param patterns Список регулярных выражений
     * @return true если найдено совпадение
     */
    static boolean matches(String text, List patterns) {
        if (!text) return false
        return patterns.any { pattern -> text =~ pattern }
    }

    /**
     * Определяет категорию ответа клиента
     *
     * @param text Ответ клиента
     * @return Название категории или 'unknown'
     */
    static String categorize(String text) {
        if (!text) return 'unknown'

        // Проверяем в порядке приоритета
        if (matches(text, GREETINGS)) return 'greeting'
        if (matches(text, POLITE_RESPONSES)) return 'polite'
        if (matches(text, CONFIRMATIONS)) return 'confirmation'
        if (matches(text, CAPABILITY_QUESTIONS)) return 'capability_question'
        if (matches(text, SMALL_TALK)) return 'small_talk'
        if (matches(text, IDENTITY_QUESTIONS)) return 'identity_question'
        if (matches(text, PURPOSE_QUESTIONS)) return 'purpose_question'
        if (matches(text, REJECTIONS)) return 'rejection'
        if (matches(text, CLARIFICATIONS)) return 'clarification'
        if (matches(text, WAIT_REQUESTS)) return 'wait'
        if (matches(text, BUSY_RESPONSES)) return 'busy'
        if (matches(text, BOT_QUESTIONS)) return 'bot_question'

        return 'unknown'
    }

    /**
     * Получить все совпадающие категории (может быть несколько)
     *
     * @param text Ответ клиента
     * @return Список категорий
     */
    static List<String> categorizeAll(String text) {
        if (!text) return ['unknown']

        def categories = []
        if (matches(text, GREETINGS)) categories << 'greeting'
        if (matches(text, POLITE_RESPONSES)) categories << 'polite'
        if (matches(text, CONFIRMATIONS)) categories << 'confirmation'
        if (matches(text, CAPABILITY_QUESTIONS)) categories << 'capability_question'
        if (matches(text, SMALL_TALK)) categories << 'small_talk'
        if (matches(text, IDENTITY_QUESTIONS)) categories << 'identity_question'
        if (matches(text, PURPOSE_QUESTIONS)) categories << 'purpose_question'
        if (matches(text, REJECTIONS)) categories << 'rejection'
        if (matches(text, CLARIFICATIONS)) categories << 'clarification'
        if (matches(text, WAIT_REQUESTS)) categories << 'wait'
        if (matches(text, BUSY_RESPONSES)) categories << 'busy'
        if (matches(text, BOT_QUESTIONS)) categories << 'bot_question'

        return categories ?: ['unknown']
    }
}

